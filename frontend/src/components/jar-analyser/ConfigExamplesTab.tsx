import { useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import api from '@/lib/api'
import CodeViewer from '@/components/CodeViewer'
import type { ConfigExample } from './types'

interface Props {
  reportId: string
  subReportId: string
}

export default function ConfigExamplesTab({ reportId, subReportId }: Props) {
  const [selected, setSelected] = useState<string | null>(null)

  const { data: examples = [] } = useQuery<ConfigExample[]>({
    queryKey: ['config-examples', reportId, subReportId],
    queryFn: () => api.get(`/jar-analyser/reports/${reportId}/sub-reports/${subReportId}/config-examples`).then(r => r.data),
  })

  const activeClass = selected ?? examples[0]?.root_class_name ?? null

  const { data: detail, isLoading: detailLoading } = useQuery<ConfigExample>({
    queryKey: ['config-example-detail', reportId, subReportId, activeClass],
    queryFn: () => api.get(
      `/jar-analyser/reports/${reportId}/sub-reports/${subReportId}/config-examples/${encodeURIComponent(activeClass!)}`
    ).then(r => r.data),
    enabled: !!activeClass,
  })

  if (examples.length === 0) {
    return (
      <div className="bg-white border border-gray-200 rounded-lg p-8 text-center text-sm text-gray-400">
        No config/design documents discovered for this service.
      </div>
    )
  }

  return (
    <div className="grid grid-cols-3 gap-4">
      <div className="col-span-1 bg-white border border-gray-200 rounded-lg overflow-hidden">
        <div className="px-3 py-2 border-b border-gray-200 bg-gray-50 text-xs font-medium text-gray-600">
          Discovered documents
        </div>
        <div className="max-h-[65vh] overflow-y-auto">
          {examples.map(ex => (
            <button
              key={ex.root_class_name}
              onClick={() => setSelected(ex.root_class_name)}
              className={`w-full text-left px-3 py-2 text-xs font-mono flex items-center justify-between gap-2 ${
                activeClass === ex.root_class_name ? 'bg-blue-50 text-blue-700' : 'text-gray-700 hover:bg-gray-50'
              }`}
            >
              <span className="truncate">{ex.root_class_name.split('.').pop()}</span>
              <span
                className={`shrink-0 px-1.5 py-0.5 rounded text-[10px] font-medium ${
                  ex.source === 'bundled' ? 'bg-green-100 text-green-700' : 'bg-amber-100 text-amber-700'
                }`}
              >
                {ex.source === 'bundled' ? 'real' : 'synthesized'}
              </span>
            </button>
          ))}
        </div>
      </div>

      <div className="col-span-2 bg-white border border-gray-200 rounded-lg overflow-hidden" style={{ minHeight: '65vh' }}>
        {detailLoading && (
          <div className="flex items-center justify-center h-full text-sm text-gray-400 py-16">Loading…</div>
        )}
        {!detailLoading && detail && (
          <div className="h-full flex flex-col">
            <div className="px-3 py-2 border-b border-gray-200 bg-gray-50 text-xs font-mono text-gray-600 flex items-center justify-between gap-2">
              <span className="truncate">{detail.root_class_name}</span>
              <span
                className={`shrink-0 px-2 py-0.5 rounded text-[11px] font-medium font-sans ${
                  detail.source === 'bundled' ? 'bg-green-100 text-green-700' : 'bg-amber-100 text-amber-700'
                }`}
              >
                {detail.source === 'bundled' ? '✓ real, bundled with the jar' : '⚗ synthesized'}
              </span>
            </div>
            {detail.source === 'bundled' ? (
              <div className="px-3 py-2 bg-green-50 border-b border-green-200 text-xs text-green-800">
                This is a real example document shipped inside the jar itself — not generated by this tool.
              </div>
            ) : (
              <details className="px-3 py-2 bg-amber-50 border-b border-amber-200 text-xs text-amber-800">
                <summary className="cursor-pointer font-medium">
                  ⓘ Synthesized — structurally valid, not from a real deployment
                </summary>
                <p className="mt-1.5 text-amber-700">
                  Built from this jar's own structure — required fields, real enum/discriminator values, no
                  invented ones. Fields referencing another system's own catalog (e.g. a blueprint ID registered
                  elsewhere) are placeholders, not real values. Never AI-generated — see the full comment header
                  in the document below for detail.
                </p>
              </details>
            )}
            <div style={{ height: '56vh' }}>
              <CodeViewer content={detail.content ?? ''} format={detail.format || 'yaml'} readOnly />
            </div>
          </div>
        )}
      </div>
    </div>
  )
}
