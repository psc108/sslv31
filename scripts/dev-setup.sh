#!/bin/bash
# SSL Certificate Manager — Development Setup & Start
# Run from project root: bash scripts/dev-setup.sh
#
# This script:
#   1. Creates Python venv and installs backend dependencies
#   2. Installs frontend dependencies
#   3. Generates .env with secrets if not present
#   4. Creates data directories
#   5. Runs database migrations
#   6. Starts backend and frontend dev servers

set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BACKEND_DIR="${PROJECT_ROOT}/backend"
FRONTEND_DIR="${PROJECT_ROOT}/frontend"
DATA_DIR="/tmp/certmanager"

echo "=== SSL Certificate Manager — Dev Setup ==="
echo "  Project: ${PROJECT_ROOT}"
echo ""

# --- Python venv ---
echo "[1/6] Python environment..."
if [ ! -d "${BACKEND_DIR}/venv" ]; then
    python3 -m venv "${BACKEND_DIR}/venv"
    echo "  Created venv"
fi
"${BACKEND_DIR}/venv/bin/pip" install --quiet --upgrade pip
"${BACKEND_DIR}/venv/bin/pip" install --quiet -r "${BACKEND_DIR}/requirements.txt"
echo "  ✓ Backend dependencies installed"

# --- Frontend ---
echo "[2/6] Frontend dependencies..."
if [ ! -d "${FRONTEND_DIR}/node_modules" ]; then
    cd "${FRONTEND_DIR}" && npm install --quiet
    cd "${PROJECT_ROOT}"
    echo "  ✓ Frontend dependencies installed"
else
    echo "  ✓ Already installed (node_modules exists)"
fi

# --- Generate .env ---
echo "[3/6] Environment configuration..."
ENV_FILE="${BACKEND_DIR}/.env"
if [ ! -f "${ENV_FILE}" ]; then
    MASTER_KEY=$("${BACKEND_DIR}/venv/bin/python3" -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())")
    API_KEY=$("${BACKEND_DIR}/venv/bin/python3" -c "import secrets; print(secrets.token_urlsafe(32))")

    cat > "${ENV_FILE}" << EOF
# Auto-generated by dev-setup.sh — $(date -Iseconds)
CERT_MASTER_KEY=${MASTER_KEY}
API_KEY=${API_KEY}
DATA_DIR=${DATA_DIR}
BACKUP_DIR=${DATA_DIR}/backups
LOG_FILE=${DATA_DIR}/app.log
LOG_LEVEL=DEBUG
BASE_URL=https://localhost
BOOTSTRAP_IP=127.0.0.1
EOF
    echo "  ✓ Generated ${ENV_FILE}"
    echo ""
    echo "  ┌─────────────────────────────────────────────────────┐"
    echo "  │ API_KEY=${API_KEY}"
    echo "  │ Save this — needed for API requests.                │"
    echo "  └─────────────────────────────────────────────────────┘"
    echo ""
else
    echo "  ✓ ${ENV_FILE} already exists"
fi

# --- Data directories ---
echo "[4/6] Data directories..."
mkdir -p "${DATA_DIR}"/{self,exports,backups}
echo "  ✓ ${DATA_DIR} ready"

# --- Database migrations ---
echo "[5/6] Database migrations..."
cd "${BACKEND_DIR}"
"${BACKEND_DIR}/venv/bin/alembic" upgrade head
echo "  ✓ Database schema up to date"

# --- Start servers ---
echo "[6/6] Starting services..."
echo ""
echo "  Backend:  http://localhost:8000"
echo "  API docs: http://localhost:8000/api/docs"
echo "  Frontend: http://localhost:3000"
echo ""
echo "  Press Ctrl+C to stop both servers."
echo ""

# Start backend in background
cd "${BACKEND_DIR}"
"${BACKEND_DIR}/venv/bin/uvicorn" app.main:app --reload --host 0.0.0.0 --port 8000 &
BACKEND_PID=$!

# Start frontend in background
cd "${FRONTEND_DIR}"
npm run dev &
FRONTEND_PID=$!

# Trap Ctrl+C to kill both
cleanup() {
    echo ""
    echo "Shutting down..."
    kill ${BACKEND_PID} 2>/dev/null || true
    kill ${FRONTEND_PID} 2>/dev/null || true
    wait ${BACKEND_PID} 2>/dev/null || true
    wait ${FRONTEND_PID} 2>/dev/null || true
    echo "Done."
}
trap cleanup EXIT INT TERM

# Wait for either to exit
wait
